      url "https://github.com/shellfu/sinter/releases/download/v#{version}/sinter-x86_64-apple-darwin.tar.gz"
      sha256 "d5e60bb79d92d4cfd1188595b5a2bc940243941f61cf0c0c42e9f8d24611124d"
