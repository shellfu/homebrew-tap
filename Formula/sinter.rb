      url "https://github.com/shellfu/sinter/releases/download/v#{version}/sinter-aarch64-unknown-linux-musl.tar.gz"
      sha256 "431c55f46e66d7e9601ca266572453a8fedbb0328d62cd7eb76986c1b99a372c"
